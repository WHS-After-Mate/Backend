async function main() {
  console.log("[seedTreatmentGuides] treatment_guides upsert 중...");
  let count = 0;
  for (const [careName, days] of Object.entries(GUIDES)) {
    for (const [dayStr, content] of Object.entries(days)) {
      const day = Number(dayStr);
      const { error } = await supabase.from("treatment_guides").upsert(
        {
          care_name: careName,
          day,
          key_care: content.keyCare,
          aftercare: content.aftercare,
          precautions: content.precautions,
          updated_at: new Date().toISOString(),
        },
        { onConflict: "care_name,day" },
      );
      if (error) throw new Error(`[treatment_guides:${careName}/${day}] 실패: ${error.message}`);
      count++;
    }
  }
  console.log(`[seedTreatmentGuides] 완료 — ${count}개 행 (${Object.keys(GUIDES).length}개 시술 × 5일차)`);
}

main();
